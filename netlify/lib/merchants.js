const norm = (s) => ' ' + String(s || '').toUpperCase().replace(/[^A-Z0-9]+/g, ' ').trim() + ' ';

// Precompile: [category, normalizedPattern, wholeWord]
function compile(list) {
  const out = [];
  for (const [category, patterns] of list) {
    for (const p of patterns) {
      const np = norm(p).trim();
      if (np) out.push([category, ' ' + np + (np.length <= 4 ? ' ' : '')]);
    }
  }
  return out;
}
const SPECIFIC = compile(DIRECTORY);
const BROAD = compile(GENERIC);

function find(list, texts) {
  const hay = norm(texts.filter(Boolean).join(' '));
  for (const [category, needle] of list) if (hay.includes(needle)) return category;
  return null;
}

